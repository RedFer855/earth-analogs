// Generates the synthetic sample data served from public/data/.
//
// Every value comes from a seeded PRNG (mulberry32). Nothing here is read from, or copied from, a real ETL run:
// the Earth coordinates are random draws, not real analog sites. The files follow the field names of the
// integration plan (sections 4.3 and 4.4) so the copilot can later read real `salida.rs` output unchanged.
//
// Fields the published ETL does not provide today (N4 silica, N6 solar illumination, N7 saltation, surface
// temperature) are deliberately absent, so the copilot must report them as missing.
//
// Usage: node scripts/generate-synthetic-data.mjs

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SEED = 20261115;
const CELLS_PER_TARGET = 40;
const NOTICE =
  'Synthetic sample generated by scripts/generate-synthetic-data.mjs with a seeded PRNG. Not real data; do not cite.';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'data');

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(SEED);
const between = (lo, hi) => lo + (hi - lo) * rand();
const round = (v, digits) => Number(v.toFixed(digits));

// Targets are labels only; the Earth cells attached to them are synthetic draws.
const TARGETS = [
  { codigo: 'SHK', nombre: 'Shackleton rim (sample)', cuerpo: 'MOON', perfil: 'luna_polar', slope: [2, 24] },
  { codigo: 'MAL', nombre: 'Malapert massif (sample)', cuerpo: 'MOON', perfil: 'luna_polar', slope: [4, 28] },
  { codigo: 'NOB', nombre: 'Nobile rim (sample)', cuerpo: 'MOON', perfil: 'luna_polar', slope: [1, 18] },
  { codigo: 'JEZ', nombre: 'Jezero delta (sample)', cuerpo: 'MARS', perfil: 'marte_sedimentario', slope: [1, 22] },
  { codigo: 'GAL', nombre: 'Gale crater mound (sample)', cuerpo: 'MARS', perfil: 'marte_sedimentario', slope: [3, 34] },
  { codigo: 'UTO', nombre: 'Utopia ground ice (sample)', cuerpo: 'MARS', perfil: 'marte_hielo', slope: [0, 12] },
];

const PIN_TYPES = ['tubo_lava', 'crater_impacto', 'playa_salar'];
const PIN_LABEL = { tubo_lava: 'lava tube', crater_impacto: 'impact crater', playa_salar: 'salt playa' };

// 15 synthetic pins at random land-agnostic coordinates between 50 S and 70 N.
const pins = [];
for (let i = 0; i < 15; i += 1) {
  const tipo = PIN_TYPES[i % PIN_TYPES.length];
  const lat = round(between(-50, 70), 4);
  const lon = round(between(-180, 180), 4);
  pins.push({
    type: 'Feature',
    geometry: { type: 'Point', coordinates: [lon, lat] },
    properties: { tipo, nombre: `Synthetic ${PIN_LABEL[tipo]} ${String(i + 1).padStart(2, '0')}`, synthetic: true },
  });
}

function jitterNear(lat, lon, maxKm) {
  const dKm = between(0, maxKm);
  const bearing = between(0, 2 * Math.PI);
  const dLat = (dKm / 111.2) * Math.cos(bearing);
  const dLon = ((dKm / 111.2) * Math.sin(bearing)) / Math.max(Math.cos((lat * Math.PI) / 180), 0.2);
  return [round(lat + dLat, 4), round(((lon + dLon + 540) % 360) - 180, 4)];
}

let nextIpix = 100000;

function makeCell(target) {
  let lat;
  let lon;
  const pick = rand();
  if (pick < 0.3) {
    // Near a pin so the < 25 km pin bonus is testable.
    const pin = pins[Math.floor(rand() * pins.length)];
    [lat, lon] = jitterNear(pin.geometry.coordinates[1], pin.geometry.coordinates[0], 30);
  } else if (pick < 0.45) {
    // Above 60 N so the P-015 polar exclusion is testable.
    lat = round(between(60.5, 78), 4);
    lon = round(between(-75, 30), 4);
  } else {
    lat = round(between(-55, 60), 4);
    lon = round(between(-180, 180), 4);
  }
  const slope = between(target.slope[0], target.slope[1]);
  const rangoMissing = rand() < 0.05;
  nextIpix += 1 + Math.floor(rand() * 900);
  return {
    ipix: nextIpix,
    lat,
    lon,
    region: `Synthetic region ${String(Math.floor(rand() * 90) + 10)}`,
    similitud: round(between(0.42, 0.97), 4),
    slope_mean_deg: round(slope, 2),
    slope_std_deg: round(between(0.4, 6), 2),
    rug_rms_mean_m: round(between(0.02, 0.6), 3),
    relieve_mean_m: round(between(0.1, 3.2), 3),
    diagnostico: {
      rango_diurno_k: rangoMissing ? null : round(between(6, 50), 2),
      amp_anual_k: round(between(4, 40), 2),
    },
  };
}

function write(relPath, data) {
  const full = join(root, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, `${JSON.stringify(data, null, 1)}\n`);
}

const objetivos = [];
for (const target of TARGETS) {
  const celdas = [];
  for (let i = 0; i < CELLS_PER_TARGET; i += 1) celdas.push(makeCell(target));
  celdas.sort((a, b) => b.similitud - a.similitud);
  const archivo = `resultados/${target.perfil}/${target.codigo}.json`;
  write(archivo, {
    synthetic: true,
    notice: NOTICE,
    perfil: target.perfil,
    objetivo: { codigo: target.codigo, nombre: target.nombre, cuerpo: target.cuerpo },
    percentiles_rango_diurno_k: { p1: 8, p50: 24, p99: 45 },
    celdas,
  });
  objetivos.push({ ...target, slope: undefined, archivo, n_celdas: celdas.length });
}

write('metrics.json', {
  synthetic: true,
  notice: NOTICE,
  generado: '2026-11-15',
  objetivos: objetivos.map(({ codigo, nombre, cuerpo, perfil, archivo, n_celdas }) => ({
    codigo,
    nombre,
    cuerpo,
    perfil,
    archivo,
    n_celdas,
  })),
});

write('puntos.geojson', { type: 'FeatureCollection', synthetic: true, notice: NOTICE, features: pins });

console.log(`Wrote ${objetivos.length} targets x ${CELLS_PER_TARGET} cells and ${pins.length} pins to ${root}`);
